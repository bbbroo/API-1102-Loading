import { mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appUrl = process.env.APP_URL || "http://127.0.0.1:5173";
const apiUrl = process.env.API_URL || "http://127.0.0.1:8000/api";
const screenshotDir = resolve(scriptDir, "../docs/screenshots");
const viewport = {
  width: Number(process.env.PW_VIEWPORT_WIDTH || 1440),
  height: Number(process.env.PW_VIEWPORT_HEIGHT || 1100)
};

const demoProjectNumber = "DOC-SHOT-1102";
const demoProjectName = "Screenshot Demo - API RP 1102 Crossings";

async function api(path, options = {}) {
  const response = await fetch(`${apiUrl}${path}`, {
    headers: { "Content-Type": "application/json", ...(options.headers || {}) },
    ...options
  });
  if (!response.ok) {
    throw new Error(`${options.method || "GET"} ${path} failed: ${response.status} ${await response.text()}`);
  }
  return response.status === 204 ? null : response.json();
}

async function removePreviousDemoProjects() {
  const projects = await api("/projects");
  for (const project of projects.filter((item) => item.project_number === demoProjectNumber)) {
    await api(`/projects/${project.id}`, { method: "DELETE" });
  }
}

async function createDemoProject() {
  const project = await api("/projects", {
    method: "POST",
    body: JSON.stringify({
      project_name: demoProjectName,
      project_number: demoProjectNumber,
      client: "HDR Internal",
      location: "Rosemont, IL",
      description: "Documentation screenshot dataset with one highway crossing and one railroad crossing.",
      status: "Active"
    })
  });

  const common = {
    project_id: project.id,
    prepared_by: "Example Engineer",
    checked_by: "Example Checker",
    reviewer: "QA Review",
    date: "2026-06-10",
    revision: "0",
    status: "Draft",
    review_comments: "For documentation screenshot refresh.",
    notes: "Deterministic demo calculation generated by scripts/capture-screenshots.mjs."
  };

  const highway = await api("/calculations", {
    method: "POST",
    body: JSON.stringify({
      ...common,
      calc_number: "CALC-DOC-HWY",
      crossing_name: "Documentation Highway Crossing",
      calculation_type: "Highway",
      road_highway: "US-20 Demonstration Highway",
      railroad_route: ""
    })
  });

  const railroad = await api("/calculations", {
    method: "POST",
    body: JSON.stringify({
      ...common,
      calc_number: "CALC-DOC-RR",
      crossing_name: "Documentation Railroad Crossing",
      calculation_type: "Railroad",
      road_highway: "",
      railroad_route: "Demo Subdivision Mainline"
    })
  });

  await Promise.all([
    api(`/calculations/${highway.id}/calculate`, { method: "POST" }),
    api(`/calculations/${railroad.id}/calculate`, { method: "POST" })
  ]);

  return { project, highway, railroad };
}

async function waitForApp(page) {
  await page.goto(appUrl, { waitUntil: "networkidle" });
  await page.locator("h1", { hasText: "Engineering Dashboard" }).waitFor({ timeout: 10000 });
}

async function settle(page) {
  await page.waitForLoadState("networkidle").catch(() => {});
  await page.waitForTimeout(350);
}

async function capture(page, name) {
  await settle(page);
  await page.screenshot({
    path: resolve(screenshotDir, `${name}.png`),
    fullPage: false,
    animations: "disabled"
  });
}

async function openProjectFromProjects(page) {
  await page.getByRole("button", { name: "Projects", exact: true }).click();
  await page.locator("h1", { hasText: "Projects" }).waitFor({ timeout: 10000 });
  await settle(page);
  await capture(page, "projects");

  const row = page.locator(".project-table tbody tr", { hasText: demoProjectNumber }).first();
  await row.waitFor({ timeout: 10000 });
  await row.click();
  await page.getByText("Project Information").waitFor({ timeout: 10000 });
}

async function openCalculation(page, calcNumber) {
  const row = page.locator(".project-calcs-table tbody tr", { hasText: calcNumber }).first();
  await row.waitFor({ timeout: 10000 });
  await row.click();
  await page.getByText("Calculation Metadata").waitFor({ timeout: 10000 });
  await page.getByRole("heading", { name: "Results Summary", exact: true }).waitFor({ timeout: 10000 });
}

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport, acceptDownloads: true });
let demoProjectId = null;

try {
  await mkdir(screenshotDir, { recursive: true });
  await removePreviousDemoProjects();
  const demo = await createDemoProject();
  demoProjectId = demo.project.id;

  await waitForApp(page);
  await capture(page, "dashboard");

  await openProjectFromProjects(page);
  await capture(page, "project-detail");

  await openCalculation(page, "CALC-DOC-HWY");
  await page.getByRole("heading", { name: "F. Highway Loading", exact: true }).waitFor({ timeout: 10000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await capture(page, "highway-calculation");

  await page.getByRole("heading", { name: "Results Summary", exact: true }).scrollIntoViewIfNeeded();
  await page.evaluate(() => window.scrollBy(0, -120));
  await page.getByRole("heading", { name: "Advanced Calculation View", exact: true }).waitFor({ timeout: 10000 });
  await capture(page, "results-advanced");

  await page.getByRole("button", { name: "Report", exact: true }).click();
  await page.getByText("Back to Calculation").waitFor({ timeout: 10000 });
  await page.locator(".report-page").waitFor({ timeout: 10000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await capture(page, "report-preview");

  await page.getByRole("button", { name: "Back to Calculation", exact: true }).click();
  await page.getByRole("button", { name: "Back", exact: true }).click();
  await page.getByText("Project Information").waitFor({ timeout: 10000 });
  await openCalculation(page, "CALC-DOC-RR");
  await page.getByRole("heading", { name: "F. Railroad Loading", exact: true }).waitFor({ timeout: 10000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await capture(page, "railroad-calculation");

  console.log(JSON.stringify({
    ok: true,
    screenshotDir,
    files: [
      "dashboard.png",
      "projects.png",
      "project-detail.png",
      "highway-calculation.png",
      "railroad-calculation.png",
      "results-advanced.png",
      "report-preview.png"
    ]
  }, null, 2));
} finally {
  await browser.close();
  if (demoProjectId !== null) {
    await api(`/projects/${demoProjectId}`, { method: "DELETE" }).catch((error) => {
      console.warn(`Could not delete screenshot demo project ${demoProjectId}: ${error.message}`);
    });
  }
}
